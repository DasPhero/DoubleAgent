package core

import (
	"fmt"
	"strconv"
	"strings"
)

// ProxychainsChainType specifies the chaining mode in proxychains.conf (F-14).
type ProxychainsChainType string

const (
	ChainStrict     ProxychainsChainType = "strict_chain"
	ChainDynamic    ProxychainsChainType = "dynamic_chain"
	ChainRandom     ProxychainsChainType = "random_chain"
	ChainRoundRobin ProxychainsChainType = "round_robin_chain"
)

// ProxychainsProxyEntry represents a single proxy hop in proxychains.conf (F-14).
type ProxychainsProxyEntry struct {
	Type     string `json:"type"` // "socks5", "socks4", "http"
	Host     string `json:"host"`
	Port     uint16 `json:"port"`
	Username string `json:"username,omitempty"`
	Password string `json:"password,omitempty"`
	Comment  string `json:"comment,omitempty"`
}

// ProxychainsExportOptions configures the generation of proxychains.conf (F-14).
type ProxychainsExportOptions struct {
	ChainType         ProxychainsChainType    `json:"chainType"`
	ProxyDNS          bool                    `json:"proxyDNS"`
	QuietMode         bool                    `json:"quietMode"`
	TCPReadTimeout    int                     `json:"tcpReadTimeout"`
	TCPConnectTimeout int                     `json:"tcpConnectTimeout"`
	Proxies           []ProxychainsProxyEntry `json:"proxies"`
}

// GenerateProxychainsConfig produces standard RFC-compliant proxychains / proxychains4 configuration text (F-14).
func GenerateProxychainsConfig(opts ProxychainsExportOptions) string {
	var b strings.Builder

	chainType := opts.ChainType
	if chainType == "" {
		chainType = ChainStrict
	}

	tcpRead := opts.TCPReadTimeout
	if tcpRead <= 0 {
		tcpRead = 15000
	}
	tcpConnect := opts.TCPConnectTimeout
	if tcpConnect <= 0 {
		tcpConnect = 8000
	}

	b.WriteString("# ----------------------------------------------------------------------------\n")
	b.WriteString("# proxychains.conf - generated by DoubleAgent SSH Client (F-14)\n")
	b.WriteString("# Compatible with proxychains and proxychains-ng (proxychains4)\n")
	b.WriteString("# ----------------------------------------------------------------------------\n\n")

	b.WriteString(string(chainType) + "\n\n")

	if opts.ProxyDNS {
		b.WriteString("# Proxy DNS requests - no leak for DNS data\n")
		b.WriteString("proxy_dns\n\n")
	}

	if opts.QuietMode {
		b.WriteString("# Quiet mode (no output from library)\n")
		b.WriteString("quiet_mode\n\n")
	}

	b.WriteString("# Timeout configuration in milliseconds\n")
	b.WriteString(fmt.Sprintf("tcp_read_time_out %d\n", tcpRead))
	b.WriteString(fmt.Sprintf("tcp_connect_time_out %d\n\n", tcpConnect))

	b.WriteString("[ProxyList]\n")
	b.WriteString("# Protocol  IP/Host          Port   [Username] [Password]\n")

	if len(opts.Proxies) == 0 {
		b.WriteString("# No proxies configured. Add entries below, e.g.:\n")
		b.WriteString("# socks5    127.0.0.1        1080\n")
	} else {
		for _, p := range opts.Proxies {
			proto := strings.ToLower(strings.TrimSpace(p.Type))
			if proto == "" {
				proto = "socks5"
			}
			host := strings.TrimSpace(p.Host)
			if host == "" {
				host = "127.0.0.1"
			}
			port := p.Port
			if port == 0 {
				port = 1080
			}

			line := fmt.Sprintf("%-10s %-16s %-6d", proto, host, port)
			if p.Username != "" {
				line += " " + p.Username
				if p.Password != "" {
					line += " " + p.Password
				}
			}
			if p.Comment != "" {
				line += " # " + p.Comment
			}
			b.WriteString(line + "\n")
		}
	}

	return b.String()
}

// BuildDefaultProxychainsOptions extracts available SOCKS5 forward rules and SOCKS5 proxy profiles from the vault (F-14).
func BuildDefaultProxychainsOptions(payload VaultPayload) ProxychainsExportOptions {
	opts := ProxychainsExportOptions{
		ChainType:         ChainStrict,
		ProxyDNS:          true,
		QuietMode:         false,
		TCPReadTimeout:    15000,
		TCPConnectTimeout: 8000,
		Proxies:           make([]ProxychainsProxyEntry, 0),
	}

	// 1. Dynamic forwarding rules (-D SOCKS5 proxies)
	for _, rule := range payload.ForwardRules {
		if rule.Type == ForwardDynamic {
			bindAddr := rule.BindAddress
			if bindAddr == "" || bindAddr == "0.0.0.0" {
				bindAddr = "127.0.0.1"
			}
			comment := rule.Label
			if comment == "" && rule.HostID != "" {
				comment = "Dynamic -D rule for host " + rule.HostID
			}
			opts.Proxies = append(opts.Proxies, ProxychainsProxyEntry{
				Type:    "socks5",
				Host:    bindAddr,
				Port:    rule.BindPort,
				Comment: comment,
			})
		}
	}

	// 2. Saved SOCKS5 proxy profiles
	for _, prof := range payload.ProxyProfiles {
		if prof.Type == ProxyTypeSocks5 && prof.SocksAddress != "" {
			host := prof.SocksAddress
			port := uint16(1080)
			if h, pStr, err := netSplitHostPort(prof.SocksAddress); err == nil {
				host = h
				if p, err := strconv.Atoi(pStr); err == nil && p > 0 && p <= 65535 {
					port = uint16(p)
				}
			}
			opts.Proxies = append(opts.Proxies, ProxychainsProxyEntry{
				Type:     "socks5",
				Host:     host,
				Port:     port,
				Username: prof.SocksUsername,
				Password: prof.SocksPassword,
				Comment:  "Profile: " + prof.Name,
			})
		}
	}

	// If no proxies found, add default fallback 127.0.0.1:1080
	if len(opts.Proxies) == 0 {
		opts.Proxies = append(opts.Proxies, ProxychainsProxyEntry{
			Type:    "socks5",
			Host:    "127.0.0.1",
			Port:    1080,
			Comment: "Default DoubleAgent SOCKS5 listener",
		})
	}

	return opts
}

func netSplitHostPort(addr string) (string, string, error) {
	idx := strings.LastIndex(addr, ":")
	if idx == -1 {
		return addr, "1080", nil
	}
	return addr[:idx], addr[idx+1:], nil
}
